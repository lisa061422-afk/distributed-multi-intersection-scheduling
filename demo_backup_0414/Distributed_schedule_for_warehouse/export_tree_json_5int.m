function export_tree_json_5int(LocalTreeCache, group, scene, out_path)
% export_tree_json_5int  Export decision-tree data for 5 intersections.
%   Same logic as export_tree_json.m but iterates agents 1:5 and
%   uses 'tr_' prefix in the ALL_TREE_DATA key to avoid collision
%   with warehouse-mode tree data.
%
% INPUTS
%   LocalTreeCache  cell or struct array — LocalTreeCache{1..5} used
%   group           string e.g. '15r'
%   scene           string e.g. 'S1'
%   out_path        full path to output .js file

fid = fopen(out_path, 'w');
if fid < 0
    error('export_tree_json_5int: cannot open for writing: %s', out_path);
end

fprintf(fid, '// Decision-tree data (5-int) — group=%s  scene=%s\n', group, scene);
fprintf(fid, '// Auto-generated by export_tree_json_5int.m — do not edit manually.\n');
fprintf(fid, 'window.ALL_TREE_DATA = window.ALL_TREE_DATA || {};\n');
fprintf(fid, 'window.ALL_TREE_DATA["tr_%s_%s"] = {\n', group, scene);
fprintf(fid, '  "group": "%s", "scene": "%s",\n', group, scene);
fprintf(fid, '  "intersections": {\n');

for agent_i = 1:5
    if agent_i > 1
        fprintf(fid, ',\n');
    end

    % Support both cell array and struct array for LocalTreeCache
    if iscell(LocalTreeCache) && numel(LocalTreeCache) >= agent_i
        cache = LocalTreeCache{agent_i};
    elseif isstruct(LocalTreeCache) && numel(LocalTreeCache) >= agent_i
        cache = LocalTreeCache(agent_i);
    else
        cache = [];
    end

    if isempty(cache) || ~isstruct(cache) || ~isfield(cache, 'NODES')
        fprintf(fid, '    "%d": null', agent_i);
        continue;
    end

    NODES     = cache.NODES;
    Path      = cache.Path;
    num_nodes = size(NODES, 1);

    % ── Build children map ──────────────────────────────────────────────
    children = cell(num_nodes, 1);
    for i = 1:num_nodes
        p = NODES{i}{7};
        if p > 0 && p <= num_nodes
            children{p} = [children{p}, i];
        end
    end

    % ── Identify display nodes ──────────────────────────────────────────
    is_branch = false(num_nodes, 1);
    is_leaf   = false(num_nodes, 1);
    for i = 1:num_nodes
        nc = numel(children{i});
        if nc >= 2, is_branch(i) = true; end
        if nc == 0, is_leaf(i)   = true; end
    end

    is_display    = false(num_nodes, 1);
    is_display(1) = true;
    for i = 1:num_nodes
        if is_branch(i)
            is_display(i)           = true;
            is_display(children{i}) = true;
        end
        if is_leaf(i)
            is_display(i) = true;
        end
    end

    display_nodes = find(is_display);
    nd = numel(display_nodes);

    % Map original NODES index → 1-based compressed index
    old2new = zeros(num_nodes, 1);
    for k = 1:nd
        old2new(display_nodes(k)) = k;
    end

    % ── Compressed edges ────────────────────────────────────────────────
    src_list = [];
    dst_list = [];
    for k = 1:nd
        orig = display_nodes(k);
        if orig == 1, continue; end
        p = NODES{orig}{7};
        while p > 0 && ~is_display(p)
            p = NODES{p}{7};
        end
        if p > 0 && is_display(p)
            src_list = [src_list, old2new(p)];   %#ok<AGROW>
            dst_list = [dst_list, old2new(orig)]; %#ok<AGROW>
        end
    end

    % ── Optimal path in compressed indices ──────────────────────────────
    path_comp = [];
    if ~isempty(Path)
        valid_mask = (Path >= 1) & (Path <= num_nodes) & is_display(Path)';
        path_disp  = Path(valid_mask);
        path_comp  = old2new(path_disp);
        path_comp  = path_comp(path_comp > 0);
    end
    path_set = false(nd, 1);
    if ~isempty(path_comp)
        path_set(path_comp) = true;
    end

    % ── Write JSON object ────────────────────────────────────────────────
    fprintf(fid, '    "%d": {\n', agent_i);

    % nodes array
    fprintf(fid, '      "nodes": [\n');
    for k = 1:nd
        orig   = display_nodes(k);
        tw_val = NODES{orig}{5};
        f_val  = NODES{orig}{12};
        comma  = ''; if k < nd, comma = ','; end
        fprintf(fid, '        {"id":%d,"orig":%d,"tw":%.3f,"f":%.3f,"isPath":%s}%s\n', ...
            k, orig, tw_val, f_val, bool2str(path_set(k)), comma);
    end
    fprintf(fid, '      ],\n');

    % edges array
    fprintf(fid, '      "edges": [\n');
    ne = numel(src_list);
    for e = 1:ne
        comma = ''; if e < ne, comma = ','; end
        fprintf(fid, '        [%d,%d]%s\n', src_list(e), dst_list(e), comma);
    end
    fprintf(fid, '      ],\n');

    % path array
    fprintf(fid, '      "path": [');
    if ~isempty(path_comp)
        fprintf(fid, '%d', path_comp(1));
        for k = 2:numel(path_comp)
            fprintf(fid, ',%d', path_comp(k));
        end
    end
    fprintf(fid, ']\n');

    fprintf(fid, '    }');
end

fprintf(fid, '\n  }\n};\n');
fclose(fid);
fprintf('Tree JS exported (5-int): %s\n', out_path);
end

% ── helper ──────────────────────────────────────────────────────────────────
function s = bool2str(b)
if b, s = 'true'; else, s = 'false'; end
end
