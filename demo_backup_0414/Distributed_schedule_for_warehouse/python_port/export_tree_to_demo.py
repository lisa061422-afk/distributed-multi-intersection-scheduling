"""
Port of export_tree_json.m + export_interactive_tree.m.

Generates the two .js files demo's "Tree" panel needs for a given case:
  schedules/tree_<group>_<scene>_optimal.js          (static viewer)
  schedules/interactive_tree_<group>_<scene>.js      (interactive explorer)

Input is the per-int LocalTreeCache from ADMM (a list[n_agents] of dicts
containing 'NODES' and 'Path' from the converged ADMM run).
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import List


def _bool(b: bool) -> str:
    return 'true' if b else 'false'


def export_tree_static_js(local_tree_cache, group: str, scene: str,
                           out_path) -> Path:
    """Mirror of export_tree_json.m. 4-int focused (uses agents 0..3)."""
    out_path = Path(out_path).with_suffix('.js')
    out_path.parent.mkdir(parents=True, exist_ok=True)

    lines: List[str] = []
    lines.append(f'// Decision-tree data — group={group}  scene={scene}')
    lines.append('// Auto-generated by export_tree_to_demo.py — do not edit manually.')
    lines.append('window.ALL_TREE_DATA = window.ALL_TREE_DATA || {};')
    lines.append(f'window.ALL_TREE_DATA["{group}_{scene}"] = {{')
    lines.append(f'  "group": "{group}", "scene": "{scene}",')
    lines.append('  "intersections": {')

    int_blocks = []
    for agent_i in range(4):   # always 4 ints in 2x2 demo
        cache = (local_tree_cache[agent_i]
                 if agent_i < len(local_tree_cache) else None)
        if not cache or 'NODES' not in cache or not cache['NODES']:
            int_blocks.append(f'    "{agent_i + 1}": null')
            continue

        NODES = cache['NODES']
        Path_list = cache.get('Path') or []
        # NODES[0] is a sentinel None; real nodes live at NODES[1..max_idx]
        # with NODES[i].idx == i and NODES[i].parent in 1..max_idx (0 = root).
        max_idx = len(NODES) - 1

        # Build children map (1-indexed parent → list of 1-indexed children)
        children = [[] for _ in range(max_idx + 1)]
        for i in range(1, max_idx + 1):
            if NODES[i] is None: continue
            p = NODES[i].parent
            if 1 <= p <= max_idx:
                children[p].append(i)

        is_branch = [False] * (max_idx + 1)
        is_leaf   = [False] * (max_idx + 1)
        for i in range(1, max_idx + 1):
            if NODES[i] is None: continue
            nc = len(children[i])
            if nc >= 2: is_branch[i] = True
            if nc == 0: is_leaf[i] = True

        is_display = [False] * (max_idx + 1)
        if max_idx >= 1 and NODES[1] is not None:
            is_display[1] = True
        for i in range(1, max_idx + 1):
            if NODES[i] is None: continue
            if is_branch[i]:
                is_display[i] = True
                for c in children[i]:
                    is_display[c] = True
            if is_leaf[i]:
                is_display[i] = True

        display_nodes = [i for i in range(1, max_idx + 1) if is_display[i]]
        nd = len(display_nodes)

        # Map idx → compressed (1-based, in display order)
        old2new = [0] * (max_idx + 1)
        for k, orig in enumerate(display_nodes, start=1):
            old2new[orig] = k

        # Compressed edges
        src_list, dst_list = [], []
        for orig in display_nodes:
            if orig == 1: continue
            p = NODES[orig].parent
            while 1 <= p <= max_idx and NODES[p] is not None and not is_display[p]:
                p = NODES[p].parent
            if 1 <= p <= max_idx and NODES[p] is not None and is_display[p]:
                src_list.append(old2new[p])
                dst_list.append(old2new[orig])

        # Optimal path → compressed
        path_comp = []
        for orig in Path_list:
            if 1 <= orig <= max_idx and NODES[orig] is not None and is_display[orig]:
                cc = old2new[orig]
                if cc > 0:
                    path_comp.append(cc)
        path_set = set(path_comp)

        # Per-int JSON
        node_lines = []
        for k, orig in enumerate(display_nodes, start=1):
            node = NODES[orig]
            tw = float(node.tw); f = float(node.f)
            comma = ',' if k < nd else ''
            node_lines.append(
                f'        {{"id":{k},"orig":{orig},"tw":{tw:.3f},"f":{f:.3f},'
                f'"isPath":{_bool(k in path_set)}}}{comma}')
        edge_lines = []
        for e, (s, d) in enumerate(zip(src_list, dst_list)):
            comma = ',' if e < len(src_list) - 1 else ''
            edge_lines.append(f'        [{s},{d}]{comma}')

        # Trivial-tree visibility fix
        if nd == 1 and node_lines:
            line0 = node_lines[0].rstrip(',').rstrip()
            import re as _re
            o_m = _re.search(r'"orig":(\d+)', line0)
            t_m = _re.search(r'"tw":([\d.\-]+)', line0)
            f_m = _re.search(r'"f":([\d.\-]+)', line0)
            if o_m and t_m and f_m:
                orig = int(o_m.group(1)); tw = float(t_m.group(1)); f = float(f_m.group(1))
                node_lines = [
                    f'        {{"id":1,"orig":{orig},"tw":{tw:.3f},"f":{f:.3f},"isPath":true}},',
                    f'        {{"id":2,"orig":{orig},"tw":{tw:.3f},"f":{f:.3f},"isPath":true}}',
                ]
                edge_lines = ['        [1,2]']
                path_comp = [1, 2]

        block = [
            f'    "{agent_i + 1}": {{',
            '      "nodes": [',
            *node_lines,
            '      ],',
            '      "edges": [',
            *edge_lines,
            '      ],',
            '      "path": [' + ','.join(str(x) for x in path_comp) + ']',
            '    }',
        ]
        int_blocks.append('\n'.join(block))

    lines.append(',\n'.join(int_blocks))
    lines.append('  }')
    lines.append('};')
    out_path.write_text('\n'.join(lines) + '\n')
    print(f'Tree static JS exported: {out_path}')
    return out_path


